-- ============================================================================
-- MINDBLOOM DATABASE SCHEMA (PHASE 3)
-- Project: MindBloom — AI-Powered Cognitive & Memory Assistance Platform
-- Target RDBMS: MySQL 8.0+
-- Description: Creates the 'mindbloom_db' database and core tables for
--              user profiles and cognitive game sessions.
-- ============================================================================

-- 1. Create the Database
CREATE DATABASE IF NOT EXISTS mindbloom_db
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE mindbloom_db;

-- ----------------------------------------------------------------------------
-- 2. USERS TABLE
-- Stores profile information for elderly patients and family caregivers.
-- Note: Authentication credentials/passwords are reserved for later phases.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  user_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL COMMENT 'Full display name of the user',
  email VARCHAR(150) NOT NULL UNIQUE COMMENT 'Unique contact or login email',
  user_type ENUM('elderly', 'caregiver') NOT NULL DEFAULT 'elderly' COMMENT 'Role: elderly patient or caregiver',
  password_hash VARCHAR(255) NULL DEFAULT NULL COMMENT 'Bcrypt hashed password',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT 'Record registration timestamp',
  
  -- Index for fast lookups by email
  INDEX idx_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 3. GAME SESSIONS TABLE
-- Records individual gameplay runs generated by frontend cognitive games.
-- This data directly feeds subsequent AI/ML adaptive difficulty training.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS game_sessions (
  session_id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL COMMENT 'Foreign key to users table',
  game_name VARCHAR(50) NOT NULL DEFAULT 'Memory Match' COMMENT 'Name of the cognitive game played',
  difficulty VARCHAR(20) NOT NULL COMMENT 'Difficulty level: easy, medium, hard',
  score INT NOT NULL DEFAULT 0 COMMENT 'Calculated game score (non-negative)',
  accuracy DECIMAL(5, 2) NOT NULL DEFAULT 0.00 COMMENT 'Matching accuracy percentage (0.00 to 100.00)',
  response_time INT NOT NULL DEFAULT 0 COMMENT 'Total time taken in seconds',
  total_attempts INT NOT NULL DEFAULT 0 COMMENT 'Number of pair flip attempts',
  mistakes INT NOT NULL DEFAULT 0 COMMENT 'Number of mismatched flip attempts',
  hints_used INT NOT NULL DEFAULT 0 COMMENT 'Number of hints requested during session',
  matched_pairs INT NOT NULL DEFAULT 0 COMMENT 'Number of pairs successfully matched',
  total_pairs INT NOT NULL COMMENT 'Total pairs required to complete game',
  recommended_difficulty VARCHAR(20) NULL DEFAULT NULL COMMENT 'AI Random Forest suggested difficulty for next round',
  started_at DATETIME NULL COMMENT 'Timestamp when user started playing',
  completed_at DATETIME NULL COMMENT 'Timestamp when user finished playing',
  client_session_id VARCHAR(64) NULL DEFAULT NULL COMMENT 'Unique client-generated session identifier for deduplication',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT 'Timestamp when session was saved to database',

  -- Foreign Key Constraint
  CONSTRAINT fk_game_sessions_user
    FOREIGN KEY (user_id) REFERENCES users(user_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

  -- Data Integrity Constraints
  CONSTRAINT chk_difficulty CHECK (difficulty IN ('easy', 'medium', 'hard')),
  CONSTRAINT chk_score CHECK (score >= 0),
  CONSTRAINT chk_accuracy CHECK (accuracy >= 0.00 AND accuracy <= 100.00),
  CONSTRAINT chk_response_time CHECK (response_time >= 0),
  CONSTRAINT chk_attempts CHECK (total_attempts >= 0),
  CONSTRAINT chk_mistakes CHECK (mistakes >= 0),
  CONSTRAINT chk_hints CHECK (hints_used >= 0),
  CONSTRAINT chk_matched_pairs CHECK (matched_pairs >= 0),
  CONSTRAINT chk_total_pairs CHECK (total_pairs > 0),

  -- Performance Indexes for Analytics & History Queries
  INDEX idx_game_sessions_user_id (user_id),
  INDEX idx_game_sessions_difficulty (difficulty),
  INDEX idx_game_sessions_created_at (created_at),
  UNIQUE INDEX uq_client_session_id (client_session_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

